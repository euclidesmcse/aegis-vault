const TARGET_LOCALES = ['en', 'pt-BR', 'es', 'fr', 'zh-CN', 'hi', 'ar'];

/**
 * Set nested key in a plain object using dot-path; preserves structure.
 */
function setNestedKey(obj, dotPath, value) {
  const parts = dotPath.split('.');
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    const p = parts[i];
    if (!p) continue;
    if (cur[p] === undefined || cur[p] === null || typeof cur[p] !== 'object') cur[p] = {};
    cur = cur[p];
  }
  cur[parts[parts.length - 1]] = value;
}

let modified = 0;
for (const locale of TARGET_LOCALES) {
  const file = path.join(LOCALES_DIR, `${locale}.json`);
  const json = JSON.parse(fs.readFileSync(file, 'utf-8'));
  for (const [fullPath, table] of Object.entries(NEW_KEYS)) {
    const value = table[locale];
    if (value === undefined) continue;
    // Check if the leaf already matches.
    const parts = fullPath.split('.');
    let cur = json;
    for (let i = 0; i < parts.length - 1; i++) { cur = cur?.[parts[i]]; if (!cur) break; }
    if (cur && cur[parts[parts.length - 1]] === value) continue;
    // Use Object.assign semantics for ICU plural objects.
    if (typeof value === 'string') {
      setNestedKey(json, fullPath, value);
      modified++;
    }
  }
  fs.writeFileSync(file, JSON.stringify(json, null, 2) + '\n', 'utf-8');
}
console.log(`i18n-fixes: ${modified} modifications across ${TARGET_LOCALES.length} locales.`);
